"""
app/schemas/ai/brand_voice.py

Structured output schema for the Brand Voice Agent.
"""
from enum import Enum
from typing import List
from pydantic import BaseModel, Field


class IssueSeverity(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class BrandVoiceIssue(BaseModel):
    """
    A specific brand voice violation identified by the AI.
    """
    category: str = Field(..., min_length=1, description="The category of the issue (e.g., Tone, Terminology).")
    description: str = Field(..., min_length=1, description="A description of the issue.")
    severity: IssueSeverity = Field(..., description="The severity of the issue.")


class BrandVoiceOutput(BaseModel):
    """
    Structured output generated by the AI Brand Voice Agent.
    """
    compliant: bool = Field(..., description="Whether the original draft is fully compliant without needing changes.")
    brand_score: float = Field(..., ge=0.0, le=1.0, description="Score representing alignment with the brand kit (0.0 to 1.0).")
    revised_content: str = Field(..., min_length=1, description="The revised content, or the original content if no changes were needed.")
    issues: List[BrandVoiceIssue] = Field(default_factory=list, max_length=10, description="List of identified issues.")
    changes: List[str] = Field(default_factory=list, max_length=10, description="Summary of changes made.")
