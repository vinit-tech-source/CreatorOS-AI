"""
app/schemas/ai/content_plan.py

Structured output schema for the Content Planner Agent.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class ContentSection(BaseModel):
    """
    A single section or part of the planned content.
    """
    heading: str = Field(..., description="The heading or main idea of the section.")
    objective: str = Field(..., description="What this section aims to achieve.")
    key_points: List[str] = Field(..., description="List of specific points to cover in this section.")
    estimated_length: Optional[int] = Field(None, description="Estimated word or character length for this section.")


class ContentPlanOutput(BaseModel):
    """
    Structured output generated by the AI Content Planner Agent.
    """
    title: str = Field(..., description="The proposed title of the content.")
    content_goal: str = Field(..., description="The primary objective of the entire piece.")
    hook: str = Field(..., description="An engaging opening or hook to capture attention.")
    sections: List[ContentSection] = Field(
        ...,
        description="The structural sections of the content."
    )
    key_message: str = Field(..., description="The core takeaway message.")
    call_to_action: Optional[str] = Field(None, description="The intended CTA for the audience, if applicable.")
    content_type: str = Field(..., description="The format of the content (e.g., Thread, Carousel).")
    tone: str = Field(..., description="The overall tone of the piece.")
    platform: str = Field(..., description="The platform this content is intended for.")
    language: str = Field(..., description="The language of the content.")
    constraints: List[str] = Field(default_factory=list, description="List of hard constraints to follow.")
